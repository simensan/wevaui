void test_image_decode() {
    decodes(k_rgb_unfiltered, sizeof(k_rgb_unfiltered), 4, 3, k_rgb_unfiltered_rgba, sizeof(k_rgb_unfiltered_rgba), "truecolour, filter 0 on every row");
    decodes(k_rgb_all_filters, sizeof(k_rgb_all_filters), 4, 10, k_rgb_all_filters_rgba, sizeof(k_rgb_all_filters_rgba), "truecolour, a different filter on every row");
    decodes(k_rgba, sizeof(k_rgba), 2, 2, k_rgba_rgba, sizeof(k_rgba_rgba), "truecolour with alpha, straight through");
    decodes(k_grey, sizeof(k_grey), 2, 2, k_grey_rgba, sizeof(k_grey_rgba), "greyscale expands to RGB, opaque");
    decodes(k_grey_alpha, sizeof(k_grey_alpha), 2, 1, k_grey_alpha_rgba, sizeof(k_grey_alpha_rgba), "greyscale plus alpha");
    decodes(k_indexed, sizeof(k_indexed), 3, 1, k_indexed_rgba, sizeof(k_indexed_rgba), "indexed, with a tRNS shorter than the palette");
    decodes(k_stored_block, sizeof(k_stored_block), 2, 1, k_stored_block_rgba, sizeof(k_stored_block_rgba), "level 0, so the deflate stream is a STORED block");
    decodes(k_noisy_dynamic, sizeof(k_noisy_dynamic), 64, 48, k_noisy_dynamic_rgba, sizeof(k_noisy_dynamic_rgba), "noise at level 9, which cannot be coded with the fixed tables");

    // ---- what it must REFUSE rather than guess at ----------------------
    //
    // A refused image degrades to the flat fill the engine already drew, so
    // refusing is a real behaviour and not just an absence.
    CHECK(!decode_png(nullptr, 0).valid());
    CHECK(!decode_png(k_rgba, 4).valid());                       // truncated signature

    std::vector<uint8_t> not_png(k_rgba, k_rgba + sizeof(k_rgba));
    not_png[1] = 'X';
    CHECK(!decode_png(not_png.data(), not_png.size()).valid());  // wrong signature

    // A truncated file: the header survives, the pixel data does not.
    std::vector<uint8_t> cut(k_noisy_dynamic, k_noisy_dynamic + 60);
    CHECK(!decode_png(cut.data(), cut.size()).valid());

    // Corrupt the middle of the compressed stream. Inflate must fail rather
    // than read off the end of anything.
    std::vector<uint8_t> corrupt(k_noisy_dynamic, k_noisy_dynamic + sizeof(k_noisy_dynamic));
    for (size_t i = 60; i < corrupt.size() - 12 && i < 200; ++i) corrupt[i] ^= 0x5A;
    const DecodedImage from_corrupt = decode_png(corrupt.data(), corrupt.size());
    CHECK(!from_corrupt.valid() || from_corrupt.rgba.size() == sizeof(k_noisy_dynamic_rgba));

    // ---- inflate on its own --------------------------------------------
    std::vector<uint8_t> round_trip;
    CHECK(!inflate_zlib(nullptr, 0, &round_trip));
    const uint8_t bad_header[] = {0x00, 0x00};
    CHECK(!inflate_zlib(bad_header, 2, &round_trip));
}
