// One image, decoded and compared pixel for pixel.
void decodes(const uint8_t* data, size_t size, int width, int height, const uint8_t* want,
             size_t want_size, const char* what) {
    const DecodedImage got = decode_png(data, size);
    if (!got.valid()) {
        ::wevatest::check(false, what, __FILE__, __LINE__);
        std::printf("     %s: did not decode at all\n", what);
        return;
    }
    CHECK(got.width == width);
    CHECK(got.height == height);
    CHECK(got.rgba.size() == want_size);
    if (got.rgba.size() != want_size) return;
    for (size_t i = 0; i < want_size; ++i) {
        if (got.rgba[i] != want[i]) {
            ::wevatest::check(false, what, __FILE__, __LINE__);
            std::printf("     %s: byte %zu is %u, expected %u\n", what, i,
                        static_cast<unsigned>(got.rgba[i]), static_cast<unsigned>(want[i]));
            return;
        }
    }
    ::wevatest::check(true, what, __FILE__, __LINE__);
}

